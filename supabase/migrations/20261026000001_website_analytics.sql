CREATE OR REPLACE FUNCTION public.website_analytics()
RETURNS jsonb
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  WITH totals AS (
    SELECT
      count(*) AS total_page_views,
      count(DISTINCT visitor_id) AS total_unique_visitors,
      count(*) FILTER (WHERE created_at >= now() - interval '30 days') AS recent_page_views,
      count(DISTINCT visitor_id) FILTER (
        WHERE created_at >= now() - interval '30 days'
      ) AS recent_unique_visitors,
      min(created_at) AS tracking_started_at
    FROM public.site_page_views
  ),
  daily_rows AS (
    SELECT
      created_at::date AS view_date,
      count(*) AS page_views,
      count(DISTINCT visitor_id) AS unique_visitors
    FROM public.site_page_views
    WHERE created_at >= current_date - 29
    GROUP BY created_at::date
  ),
  daily AS (
    SELECT jsonb_agg(
      jsonb_build_object(
        'date', day::date,
        'pageViews', coalesce(daily_rows.page_views, 0),
        'uniqueVisitors', coalesce(daily_rows.unique_visitors, 0)
      ) ORDER BY day
    ) AS daily_data
    FROM generate_series(
      current_date - 29,
      current_date,
      interval '1 day'
    ) AS days(day)
    LEFT JOIN daily_rows ON daily_rows.view_date = day::date
  ),
  top_pages AS (
    SELECT coalesce(
      jsonb_agg(
        jsonb_build_object('path', page_path, 'pageViews', page_views)
        ORDER BY page_views DESC, page_path
      ),
      '[]'::jsonb
    ) AS page_data
    FROM (
      SELECT page_path, count(*) AS page_views
      FROM public.site_page_views
      WHERE created_at >= now() - interval '30 days'
      GROUP BY page_path
      ORDER BY page_views DESC, page_path
      LIMIT 10
    ) pages
  )
  SELECT jsonb_build_object(
    'totalPageViews', totals.total_page_views,
    'totalUniqueVisitors', totals.total_unique_visitors,
    'pageViews30Days', totals.recent_page_views,
    'uniqueVisitors30Days', totals.recent_unique_visitors,
    'trackingStartedAt', totals.tracking_started_at,
    'daily', daily.daily_data,
    'topPages', top_pages.page_data
  )
  FROM totals CROSS JOIN daily CROSS JOIN top_pages;
$$;

REVOKE ALL ON FUNCTION public.website_analytics() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.website_analytics() TO service_role;
